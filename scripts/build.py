#!/usr/bin/env python3
"""Generate per-skill metadata files and the README catalogue from skill-registry.yaml.

Writes, for every skill in the registry:
  skills/<id>/skill.meta.yaml      jurisdiction, pack, language, status, ...
  skills/<id>/agents/openai.yaml   Codex / ChatGPT display metadata
and replaces the block between the CATALOGUE markers in README.md.

Run from anywhere: python3 scripts/build.py   (needs PyYAML)
"""

import pathlib
import re
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
PLUGIN = ROOT / "plugins" / "dharmabot-legal-skills"
SKILLS = PLUGIN / "skills"
REGISTRY = PLUGIN / "skill-registry.yaml"
README = ROOT / "README.md"
START, END = "<!-- CATALOGUE:START -->", "<!-- CATALOGUE:END -->"

SHARED = ROOT / "shared" / "references"
JURISDICTION_LABEL = {
    "in": "India",
    "in-states": "India, State-aware",
    "cross-border": "India + foreign",
    "neutral": "Any",
}
HEADER = "# Generated by scripts/build.py from skill-registry.yaml. Do not edit by hand.\n"


def dump(data):
    return HEADER + yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=100)


def main():
    reg = yaml.safe_load(REGISTRY.read_text(encoding="utf-8"))
    defaults = reg.get("defaults", {})
    PACK_TITLES = {p["id"]: p["title"] for p in reg["packs"]}
    unknown = {s["pack"] for s in reg["skills"]} - set(PACK_TITLES)
    if unknown:
        sys.exit(f"skills use packs missing from the registry's packs list: {sorted(unknown)}")
    rows = []
    for s in reg["skills"]:
        sid = s["id"]
        folder = SKILLS / sid
        if not (folder / "SKILL.md").exists():
            sys.exit(f"registry lists {sid} but skills/{sid}/SKILL.md is missing")
        meta = {
            "id": sid,
            "pack": s["pack"],
            "jurisdiction": s["jurisdiction"],
            "practice_area": s["practice_area"],
            "category": s["category"],
            "language": s["language"],
            "version": reg["release"],
            "law_as_of": str(s.get("law_as_of", reg["law_as_of"])),
            "status": s.get("status", defaults.get("status")),
            "reviewed_by": s.get("reviewed_by", defaults.get("reviewed_by")),
            "verified_on": s.get("verified_on", defaults.get("verified_on")),
            "hands_off_to": s.get("hands_off_to", []),
            "license": "MIT",
            "author": "Dharmabot AI",
        }
        (folder / "skill.meta.yaml").write_text(dump(meta), encoding="utf-8")
        agents = folder / "agents"
        agents.mkdir(exist_ok=True)
        openai = {
            "interface": {
                "display_name": s["display_name"],
                "short_description": s["short"],
                "default_prompt": f"Use ${sid} to help with this. {s['default_prompt']}",
            }
        }
        (agents / "openai.yaml").write_text(dump(openai), encoding="utf-8")

        # Copy shared references into the skill so it works when installed alone.
        refs = folder / "references"
        wanted = set(s.get("shared_refs", []))
        for name in sorted(wanted):
            src = SHARED / name
            if not src.exists():
                sys.exit(f"{sid}: shared reference {name} not found in shared/references/")
            refs.mkdir(exist_ok=True)
            note = f"<!-- Generated copy of shared/references/{name} by scripts/build.py. Edit the shared file, not this copy. -->\n\n"
            (refs / name).write_text(note + src.read_text(encoding="utf-8"), encoding="utf-8")
        if refs.exists():
            for old in refs.iterdir():
                if old.name not in wanted and old.read_text(encoding="utf-8").startswith("<!-- Generated copy"):
                    old.unlink()
        rows.append(s)

    listed = {s["id"] for s in rows}
    on_disk = {p.name for p in SKILLS.iterdir() if p.is_dir()}
    if on_disk - listed:
        sys.exit(f"skills missing from registry: {sorted(on_disk - listed)}")

    # Full catalogue page.
    cat = [
        "# Skill catalogue",
        "",
        "Generated by `scripts/build.py` from `skill-registry.yaml`. Do not edit by hand.",
        "",
        f"{len(rows)} skills in {len([p for p in PACK_TITLES if any(s['pack'] == p for s in rows)])} packs.",
        "",
    ]
    summary = ["| Pack | Skills | Install with |", "| --- | --- | --- |"]
    for pack, title in PACK_TITLES.items():
        pack_rows = [s for s in rows if s["pack"] == pack]
        if not pack_rows:
            continue
        anchor = re.sub(r"[^a-z0-9 -]", "", title.lower()).replace(" ", "-")
        summary.append(f"| [{title}](docs/CATALOGUE.md#{anchor}) | {len(pack_rows)} | `--pack {pack}` |")
        cat += [f"## {title}", "", f"Pack id: `{pack}`", "", "| Skill | What it does | Jurisdiction |", "| --- | --- | --- |"]
        for s in pack_rows:
            link = f"[`{s['id']}`](../plugins/dharmabot-legal-skills/skills/{s['id']}/SKILL.md)"
            cat.append(f"| {link} | {s['short']} | {JURISDICTION_LABEL[s['jurisdiction']]} |")
        cat.append("")
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "CATALOGUE.md").write_text("\n".join(cat), encoding="utf-8")

    lines = [START, "", f"**{len(rows)} skills in {len(summary) - 2} packs.** The full list with one line per skill is in [docs/CATALOGUE.md](docs/CATALOGUE.md).", ""]
    lines += summary + ["", END]
    block = "\n".join(lines)

    text = README.read_text(encoding="utf-8")
    if START not in text or END not in text:
        sys.exit("README.md is missing the CATALOGUE markers")
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    README.write_text(head + block + tail, encoding="utf-8")
    print(f"built metadata for {len(rows)} skills and refreshed README catalogue")


if __name__ == "__main__":
    main()
